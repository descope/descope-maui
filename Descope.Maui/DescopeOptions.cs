namespace Descope.Maui;

/// <summary>
/// Configuration for a <see cref="DescopeClient"/>.
/// </summary>
public class DescopeOptions
{
    /// <summary>
    /// The ID of your Descope project. It's also the OIDC client ID unless <see cref="ClientId"/> is set.
    /// </summary>
    public string ProjectId { get; set; } = "";

    /// <summary>
    /// The client ID of a specific OIDC application in the project, as shown in the application's settings in
    /// the Descope Console. Its settings, such as the Flow Hosting URL and redirect URLs, are used for sign in.
    /// When unset the project ID is the client ID, which selects the project's default OIDC application.
    /// </summary>
    public string? ClientId { get; set; }

    /// <summary>
    /// The URI Descope redirects back to after a flow or logout completes, e.g. <c>myapp://auth</c>.
    /// Its scheme must match the one registered for the app (see <c>DescopeCallbackActivity</c> on Android).
    /// It must also be allowed in the project's approved domains or the OIDC application's redirect URLs.
    /// </summary>
    public string RedirectUri { get; set; } = "";

    /// <summary>
    /// Override for the Descope API base URL, e.g. a custom domain such as <c>https://auth.example.com</c>.
    /// When unset it's derived from <see cref="ProjectId"/>, including the region for non-US projects.
    /// </summary>
    public string? BaseUrl { get; set; }

    /// <summary>
    /// The scopes requested from the authorize endpoint.
    /// <c>descope.claims</c> adds tenants, roles and permissions, and <c>descope.custom_claims</c> adds any custom claims.
    /// </summary>
    public string Scope { get; set; } = "openid profile email descope.claims descope.custom_claims";

    /// <summary>
    /// The flow to run when <see cref="DescopeLoginOptions.FlowId"/> isn't set.
    /// When neither is set Descope uses the Flow Hosting URL configured for the project.
    /// </summary>
    public string? FlowId { get; set; }

    /// <summary>
    /// When true (the default) iOS runs the flow in an ephemeral browser session, so cookies aren't
    /// shared with Safari and the user isn't silently signed back in after logging out.
    /// It has no effect on Android.
    /// </summary>
    public bool PrefersEphemeralWebBrowserSession { get; set; } = true;

    internal string ResolvedBaseUrl => (BaseUrl ?? BaseUrlForProjectId(ProjectId)).TrimEnd('/');

    internal string ResolvedClientId => string.IsNullOrWhiteSpace(ClientId) ? ProjectId : ClientId;

    internal bool HasAppClientId => !string.IsNullOrWhiteSpace(ClientId) && ClientId != ProjectId;

    // A client ID generated by Descope is base64("{projectId}:{appId}"), optionally padded with '#' before
    // encoding. Returns null for a custom client ID, which Descope resolves to its app on the server instead.
    internal static string? AppIdFromClientId(string clientId, string projectId)
    {
        string decoded;
        try
        {
            decoded = System.Text.Encoding.UTF8.GetString(Convert.FromBase64String(clientId));
        }
        catch (FormatException)
        {
            return null;
        }
        var parts = decoded.TrimEnd('#').Split(':');
        return parts.Length == 2 && parts[0] == projectId && parts[1].Length > 0 ? parts[1] : null;
    }

    internal void Validate()
    {
        if (string.IsNullOrWhiteSpace(ProjectId))
        {
            throw new DescopeException(DescopeErrorCode.InvalidConfiguration, "DescopeOptions.ProjectId is required");
        }
        if (!Uri.TryCreate(RedirectUri, UriKind.Absolute, out _))
        {
            throw new DescopeException(DescopeErrorCode.InvalidConfiguration, "DescopeOptions.RedirectUri must be an absolute URI, e.g. myapp://auth");
        }
    }

    // Project IDs created in a non-US region embed the region code after the first character
    internal static string BaseUrlForProjectId(string projectId)
    {
        if (projectId.Length >= 32)
        {
            var region = projectId.Substring(1, 4);
            return $"https://api.{region}.descope.com";
        }
        return "https://api.descope.com";
    }
}

/// <summary>
/// Per-login options for <see cref="DescopeClient.LoginAsync"/>.
/// </summary>
public class DescopeLoginOptions
{
    /// <summary>
    /// The ID of the flow to run, e.g. <c>sign-up-or-in</c>. Overrides <see cref="DescopeOptions.FlowId"/>.
    /// </summary>
    public string? FlowId { get; set; }

    /// <summary>
    /// A tenant ID or domain. Descope skips the email screen and routes straight to that tenant's SSO.
    /// </summary>
    public string? Tenant { get; set; }

    /// <summary>
    /// Prefills the login ID (usually an email) on the flow's first screen.
    /// </summary>
    public string? LoginHint { get; set; }

    /// <summary>
    /// Extra query parameters appended to the authorize URL, e.g. <c>dynamic_val</c> for values read
    /// by a flow scriptlet. Reserved OIDC parameters such as <c>state</c> can't be overridden.
    /// </summary>
    public IDictionary<string, string> AdditionalParameters { get; set; } = new Dictionary<string, string>();
}
